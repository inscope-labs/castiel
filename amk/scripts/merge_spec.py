#!/usr/bin/env python3
"""Merge the individual spec files of one AMK spec directory into one file.

Usage:
    python3 specs/scripts/merge_spec.py --dir specs/core/amk-console
    python3 specs/scripts/merge_spec.py --dir specs/core/amk-console --check

The merged file is written to the root of the spec directory as
<dir-name>-spec-full.md. The main index file (<dir-name>.md) comes first, followed
by every other .md file in the directory in path order (numbered module files
sort naturally; 99-open-items.md sorts last). Output is deterministic: it
contains no timestamps and no commit hashes, so an unchanged source produces an
identical file.

Standard library only. Exit codes: 0 ok, 1 validation error or stale (--check),
2 usage error.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

MARKER = "GENERATED FILE - DO NOT EDIT."
FENCE = re.compile(r"^\s*(```|~~~)")
HEADING = re.compile(r"^(#{1,6})(\s+.*)$")
LINK = re.compile(r"\]\((?:\./)?([^)\s#]+\.md)(#[^)\s]*)?\)")
ID_DEF = re.compile(
    r"^\s*(?:[-*]\s+)?\*\*([A-Z]{2,6}-\d+:\d+)\*\*|^#{1,6}\s+([A-Z]{2,6}-\d+:\d+)\b",
    re.M,
)
ID_REF = re.compile(r"\b([A-Z]{2,6}-\d+:\d+)\b")


def read(path: Path) -> str:
    text = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n").replace("\r", "\n")
    return text


def sha12(data: str) -> str:
    return hashlib.sha256(data.encode("utf-8")).hexdigest()[:12]


def anchor_for(rel: Path) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", rel.with_suffix("").as_posix().lower()).strip("-")
    return "file-" + slug


def first_title(text: str, fallback: str) -> str:
    in_fence = False
    for line in text.split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        m = re.match(r"^#\s+(.*)$", line)
        if m:
            return m.group(1).strip()
    return fallback


def transform(text, src: Path, spec_dir: Path, anchors: dict, warnings: list, demote: int):
    """Demote headings and rewrite links to merged files (outside code fences)."""
    out, in_fence = [], False
    for line in text.split("\n"):
        if FENCE.match(line):
            in_fence = not in_fence
            out.append(line)
            continue
        if in_fence:
            out.append(line)
            continue
        if demote:
            m = HEADING.match(line)
            if m:
                line = "#" * min(6, len(m.group(1)) + demote) + m.group(2)

        def fix(match):
            target = (src.parent / match.group(1)).resolve()
            try:
                rel = target.relative_to(spec_dir.resolve())
            except ValueError:
                warnings.append(f"{src.name}: link outside spec directory left unchanged: {match.group(1)}")
                return match.group(0)
            if rel in anchors:
                return "](#" + anchors[rel] + ")"
            warnings.append(f"{src.name}: link to file not in merge set left unchanged: {match.group(1)}")
            return match.group(0)

        out.append(LINK.sub(fix, line))
    return "\n".join(out)


def build(spec_dir: Path, output_name: str):
    name = spec_dir.name
    main = spec_dir / f"{name}.md"
    if not main.is_file():
        raise SystemExit(f"error: main index file not found: {main}")
    out_path = spec_dir / output_name

    modules = []
    for p in sorted(spec_dir.rglob("*.md"), key=lambda q: q.relative_to(spec_dir).as_posix()):
        if p == main or p == out_path or p.name.endswith("-spec-full.md"):
            continue
        if MARKER in read(p):
            continue
        modules.append(p)

    files = [main] + modules
    rels = {p: p.relative_to(spec_dir) for p in files}
    anchors = {rels[p]: anchor_for(rels[p]) for p in files}
    texts = {p: read(p) for p in files}
    warnings, errors = [], []

    # Provenance block (content hashes only, so output is deterministic).
    lines = [f"  {rels[p].as_posix():<40} {sha12(texts[p])}" for p in files]
    overall = sha12("".join(f"{rels[p].as_posix()}\0{sha12(texts[p])}\n" for p in files))
    header = (
        "<!--\n"
        f"{MARKER}\n"
        "Merged from the individual spec files in this directory by specs/scripts/merge_spec.py.\n"
        "Edit the source files, then re-run the merge-spec workflow.\n"
        "Source files (sha256, first 12 hex):\n" + "\n".join(lines) + "\n"
        f"Merged content hash: {overall}\n"
        "-->\n"
    )

    # Contents list.
    contents = ["## Merged Contents", ""]
    for p in modules:
        title = first_title(texts[p], rels[p].stem)
        contents.append(f"- [{title}](#{anchors[rels[p]]}) (`{rels[p].as_posix()}`)")
    notice = (
        "> Merged view generated from the files in this directory. Do not edit this file; "
        "edit the source files and re-run the workflow."
    )

    # Main file: keep as is, insert notice and contents after its H1.
    main_body = transform(texts[main], main, spec_dir, anchors, warnings, demote=0)
    main_lines = main_body.split("\n")
    h1 = next((i for i, l in enumerate(main_lines) if re.match(r"^#\s+", l)), None)
    if h1 is None:
        raise SystemExit(f"error: {main.name} has no H1 title")
    merged_main = "\n".join(
        main_lines[: h1 + 1] + ["", notice, ""] + contents + [""] + main_lines[h1 + 1 :]
    )
    parts = [header + f'<a id="{anchors[rels[main]]}"></a>\n\n' + merged_main.rstrip("\n")]

    for p in modules:
        body = transform(texts[p], p, spec_dir, anchors, warnings, demote=1).strip("\n")
        parts.append(f'---\n\n<a id="{anchors[rels[p]]}"></a>\n\n{body}')

    merged = "\n\n".join(parts).rstrip("\n") + "\n"

    # Validation on the merged body (header comment excluded).
    body_only = merged[len(header):]
    defs = [a or b for a, b in ID_DEF.findall(body_only)]
    seen, dup = set(), set()
    for d in defs:
        (dup if d in seen else seen).add(d)
    for d in sorted(dup):
        errors.append(f"duplicate rule ID definition: {d}")
    prefixes = {d.split("-")[0] for d in seen}
    unresolved = sorted({r for r in ID_REF.findall(body_only) if r.split("-")[0] in prefixes and r not in seen})
    for r in unresolved:
        warnings.append(f"referenced rule ID is not defined in this spec: {r}")
    main_text = texts[main]
    for p in modules:
        if rels[p].name not in main_text:
            warnings.append(f"{rels[p].as_posix()} is not listed in {main.name}")

    return merged, out_path, errors, warnings, len(files), len(seen)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dir", required=True, help="spec directory, for example specs/core/amk-console")
    ap.add_argument("--output", help="output file name (default: <dir-name>-spec-full.md)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if the merged file is stale")
    args = ap.parse_args()

    spec_dir = Path(args.dir)
    if not spec_dir.is_dir():
        print(f"error: not a directory: {spec_dir}", file=sys.stderr)
        return 2
    output_name = args.output or f"{spec_dir.name}-spec-full.md"

    merged, out_path, errors, warnings, nfiles, nrules = build(spec_dir, output_name)
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    if errors:
        return 1

    if args.check:
        current = out_path.read_text(encoding="utf-8") if out_path.is_file() else None
        if current != merged:
            print(f"stale: {out_path} does not match its source files", file=sys.stderr)
            return 1
        print(f"up to date: {out_path}")
        return 0

    out_path.write_text(merged, encoding="utf-8", newline="\n")
    print(f"wrote {out_path} ({nfiles} files merged, {nrules} rule IDs, {len(merged.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
